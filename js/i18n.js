let current = 'en';

export function detectLanguage() {
  const prefs = navigator.languages?.length ? navigator.languages : [navigator.language || 'en'];
  for (const p of prefs) {
    const base = String(p).toLowerCase().split('-')[0];
    if (DICT[base]) return base;
  }
  return 'en';
}

/** @param {string} pref 'auto' or a language id */
export function setLanguage(pref) {
  current = pref && pref !== 'auto' && DICT[pref] ? pref : detectLanguage();
  document.documentElement.lang = current;
  return current;
}

export const getLanguage = () => current;
export const getLocale = () => LANGUAGES.find((l) => l.id === current)?.locale || 'en-US';

export function t(key, vars) {
  let s = DICT[current]?.[key] ?? DICT.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return s;
}

export function tn(key, n) {
  const form = new Intl.PluralRules(getLocale()).select(n) === 'one' ? 'one' : 'other';
  return t(`${key}_${form}`, { n });
}

// Translate elements with data-i18n (text), data-i18n-html (markup) and data-i18n-aria (aria-label).
export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
